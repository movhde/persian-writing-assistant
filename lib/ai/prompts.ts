import type { AIOperation } from "./types";

const OPERATION_INSTRUCTIONS: Record<AIOperation, string> = {
  improve: `تو یک ویراستار حرفه‌ای متون فارسی هستی. متن زیر را از نظر نگارشی، دستوری و روانی بهبود بده،
بدون اینکه معنا، لحن یا قصد نویسنده را تغییر بدهی.`,
  summarize: `تو یک دستیار خلاصه‌نویسی متون فارسی هستی. متن زیر را به‌طور خلاصه و روان بازنویسی کن
و فقط نکات اصلی و مهم را نگه دار.`,
  "tone-formal": `تو یک دستیار بازنویسی متون فارسی هستی. متن زیر را با لحنی رسمی و مؤدبانه (نگارش اداری/رسمی) بازنویسی کن،
بدون اینکه معنای اصلی آن تغییر کند.`,
  "tone-informal": `تو یک دستیار بازنویسی متون فارسی هستی. متن زیر را با لحنی محاوره‌ای و غیررسمی (دوستانه و روزمره) بازنویسی کن،
بدون اینکه معنای اصلی آن تغییر کند.`,
  simplify: `تو یک دستیار ساده‌نویسی متون فارسی هستی. متن زیر را با جملات کوتاه‌تر و کلمات ساده‌تر بازنویسی کن
تا برای همه مخاطبان قابل‌فهم باشد، بدون اینکه معنای اصلی آن از دست برود.`,
};

export function buildPrompt(operation: AIOperation, text: string): string {
  return `${OPERATION_INSTRUCTIONS[operation]}

خروجی را دقیقاً به‌صورت یک JSON معتبر با این ساختار برگردان، بدون Markdown، بدون
بک‌تیک، بدون هیچ متن دیگری قبل یا بعد از آن:

{
  "text": "متن نهایی بازنویسی‌شده",
  "changes": [
    { "before": "بخش اصلی از متن ورودی", "after": "بخش جایگزین‌شده", "reason": "دلیل کوتاه این تغییر به فارسی" }
  ]
}

"changes" باید فقط تغییرهای معنادار (نه هر کلمه) را با دلیلی کوتاه و آموزشی
فهرست کند؛ اگر تغییری معنادار وجود ندارد، آرایه‌ای خالی برگردان.

متن:
"""
${text}
"""`;
}

